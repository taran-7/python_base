import time

print("--- 1. Цикл FOR (Перебір списку) ---")
# У нас є список із попереднього уроку
fruits = ["яблуко", "банан", "вишня"]

# Читається як: "Для кожного фрукта у списку фруктів..."
for fruit in fruits:
    print(f"Я люблю їсти: {fruit}")

print("\n--- 2. Цикл FOR з range() (Повторення N разів) ---")
# range(5) створює послідовність чисел від 0 до 4 (5 не входить!)
# Це стандартний спосіб повторити дію певну кількість разів
for i in range(1, 6):
    print(f"Віджимання номер: {i}")

print("\n--- 3. Цикл WHILE (Поки умова True) ---")
battery = 30
# Цей цикл буде працювати, поки батарея більше 0
while battery > 0:
    print(f"Заряд батареї: {battery}%. Працюємо...")
    battery = battery - 10  # Важливо змінювати умову, інакше цикл буде вічним!
    time.sleep(0.5)  # Маленька пауза для ефекту

print("Батарея розряджена! Телефон вимкнено.")

print("\n--- 4. Керування циклом: BREAK та CONTINUE ---")

print("Приклад BREAK (Термінова зупинка):")
# Шукаємо число 5 і зупиняємось
for number in range(10):
    if number == 5:
        print("Знайшов число 5! Зупиняю пошук.")
        break  # Повністю викидає з циклу
    print(f"Перевіряю число: {number}")

print("\nПриклад CONTINUE (Пропуск кроку):")
# Хочемо роздрукувати тільки непарні числа
for number in range(5):
    if number % 2 == 0:  # Якщо число парне
        continue  # Пропускаємо решту коду в циклі і беремо наступне число
    print(f"Це непарне число: {number}")
