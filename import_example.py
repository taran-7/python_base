# --- 1. ПОВНИЙ ІМПОРТ (import module) ---
# Ми підключаємо весь модуль. Щоб використати функцію, треба писати "назва_модуля.функція"
import math
from random import randint, choice
import datetime as dt
from math import *

print("--- 1. import math ---")
# Використовуємо корінь квадратний (sqrt) з модуля math
result = math.sqrt(16)
print(f"Корінь з 16: {result}")
print(f"Число Пі: {math.pi}")

# --- 2. ІМПОРТ КОНКРЕТНИХ ФУНКЦІЙ (from ... import ...) ---
# Якщо нам не потрібен весь "ящик", ми беремо тільки конкретний інструмент.
# Тоді назву модуля писати вже НЕ треба.

print("\n--- 2. from random import ... ---")
# Генеруємо випадкове число від 1 до 10
random_number = randint(1, 10)
print(f"Випадкове число: {random_number}")

fruits = ["Яблуко", "Банан", "Вишня"]
# Обираємо випадковий елемент зі списку
print(f"Сьогодні ти з'їси: {choice(fruits)}")

# --- 3. ІМПОРТ З ПСЕВДОНІМОМ (import ... as ...) ---
# Якщо назва модуля довга або ми ліниві, можна дати їй коротке ім'я (нікнейм).

print("\n--- 3. import ... as ... ---")
# Замість datetime.datetime.now() пишемо dt.datetime.now()
current_time = dt.datetime.now()
print(f"Зараз: {current_time}")

# --- 4. ІМПОРТ ВСЬОГО (from ... import *) ---
# ⚠️ ОБЕРЕЖНО: Це імпортує ВСЕ з модуля.
# Це вважається поганою практикою, бо може виникнути плутанина з назвами.
# Але знати про це треба.
# Тепер ми можемо писати просто cos() замість math.cos()
print(f"Косинус 0: {cos(0)}")
